/** Optional civ list keeps only those decoded faction sheets; no argument loads all six. */
export function loadUnitAtlases(
  civs?: readonly string[],
  mode: 'match' | 'preview' = 'match',
): Promise<boolean> {
  const selection = [...new Set(civs?.length ? civs : CIV_IDS)]
    .filter((civ) => CIV_IDS.includes(civ as (typeof CIV_IDS)[number]))
    .sort();
  if (!selection.length) selection.push('roman');
  const key = mode + ':' + selection.join(',');
  if (pendingLoad?.key === key) return pendingLoad.promise;
  if (!pendingLoad && loadedCivKey === key) return Promise.resolve(true);
  const promise = performUnitLoad(selection, key, mode === 'preview');
  pendingLoad = { key, promise };
  void promise.finally(() => {
    if (pendingLoad?.promise === promise) pendingLoad = undefined;
  });
  return promise;
}

async function performUnitLoad(
  civs: readonly string[],
  civKey: string,
  preview: boolean,
): Promise<boolean> {
  const requested = new Set<string>(
    (civs?.length ? civs : CIV_IDS).filter((civ) =>
      CIV_IDS.includes(civ as (typeof CIV_IDS)[number]),
    ),
  );
  if (!requested.size) requested.add('roman');
  latestCivs = requested;
  const serial = ++requestSerial;
  const jobs: Promise<boolean>[] = [loadCivilizationUnits(requested, preview)];
  // Rome, Mongolia and the Ottomans take their idle villagers from the work
  // sheet. Persia and Tang have a separate unladen tool sheet; Roman legionaries
  // also require the shared infantry stance sheet.
  const workerKeys = preview
    ? SHEET_KEYS.filter((key) =>
        key === 'infantry' ? requested.has('roman') : TOOL_ROWS[key] === undefined,
      )
    : SHEET_KEYS;
  for (const key of workerKeys) {
    if (key !== 'infantry' && !requested.has(key)) continue;
    jobs.push(
      (async () => {
        if (actionImages.has(key)) return true;
        const image = await cachedImage(SHEETS[key]);
        if (image && serial === requestSerial) {
          actionImages.set(key, image);
          loadRevision++;
        }
        return !!image;
      })(),
    );
  }
  const loadMap = (
    sheets: Record<string, Sheet>,
    map: Map<string, HTMLImageElement>,
    keys: readonly string[],
  ) => {
    for (const key of keys.filter((key) => !!sheets[key]))
      jobs.push(
        (async () => {
          if (map.has(key)) return true;
          const image = await cachedImage(sheets[key]);
          if (image && serial === requestSerial) {
            map.set(key, image);
            loadRevision++;
          }
          return !!image;
        })(),
      );
  };
  loadMap(ARMY_SHEETS, armyImages, [...requested]);
  loadMap(MOUNTED_SHEETS, mountedImages, [...requested]);
  loadMap(TRADER_SHEETS, traderImages, [...requested]);
  const neededSiege = Object.keys(FACTION_SIEGE).filter((key) => requested.has(key.split(':')[0]));
  loadMap(FACTION_SIEGE, factionSiegeImages, neededSiege);
  const neededMotion = new Set<string>();
  for (const row of Object.values(MOTION_ROWS))
    if (!row.civ || requested.has(row.civ)) neededMotion.add(row.sheet);
  if (requested.has('persian'))
    for (const key of preview ? ['elephant_a'] : ['elephant_a', 'elephant_b', 'elephant_c'])
      neededMotion.add(key);
  loadMap(MOTION_SHEETS, motionImages, [...neededMotion]);
  const neededAttack = new Set<string>();
  if (requested.has('ottoman')) neededAttack.add('cannon');
  for (const civ of preview ? [] : requested) {
    neededAttack.add('foot_' + civ);
    neededAttack.add('mounted_' + civ);
  }
  for (const row of preview ? [] : Object.values(ATTACK_ROWS))
    if (!row.civ || requested.has(row.civ)) neededAttack.add(row.sheet);
  if (!preview && requested.has('persian')) {
    neededAttack.add('elephant_windup');
    neededAttack.add('elephant_impact');
  }
  loadMap(
    ATTACK_SHEETS,
    attackImages,
    [...neededAttack].filter((id) => !!ATTACK_SHEETS[id]),
  );

  if (!preview && requested.has('tang'))
    jobs.push(
      (async () => {
        if (tangImpactImage) return true;
        const image = await cachedImage(TANG_IMPACT);
        if (image && serial === requestSerial) {
          tangImpactImage = image;
          loadRevision++;
        }
        return !!image;
      })(),
    );
  for (const [sheet, loaded, assign] of [
    [
      TOOL_SHEET,
      () => toolImage,
      (image: HTMLImageElement | undefined) => {
        toolImage = image;
      },
    ],
    [
      CARRY_SHEET,
      () => carryImage,
      (image: HTMLImageElement | undefined) => {
        carryImage = image;
      },
    ],
    [
      WOOD_SHEET,
      () => woodImage,
      (image: HTMLImageElement | undefined) => {
        woodImage = image;
      },
    ],
  ] as const)
    if (!preview || sheet === TOOL_SHEET)
      jobs.push(
        (async () => {
          if (loaded()) return true;
          const image = await cachedImage(sheet);
          if (serial === requestSerial) {
            assign(image);
            if (image) loadRevision++;
          }
          return !!image;
        })(),
      );
  const values = await Promise.all(jobs);
  // Historical atlases are only decoded when a current source failed. New traders never use them.
  if (!values.every(Boolean) && serial === requestSerial)
    await Promise.all(
      KEYS.map(async (key) => {
        if (images.has(key)) return;
        const image = await cachedImage({
          file: FALLBACK_ATLASES[key],
          width: 887,
          height: 1774,
          bodyHeight: 1,
          frames: [],
        });
        if (image && serial === requestSerial) {
          images.set(key, image);
          loadRevision++;
        }
      }),
    );
  if (serial === requestSerial) {
    if (values.every(Boolean)) images.clear();
    for (const map of [armyImages, mountedImages, traderImages])
      for (const key of map.keys()) if (!latestCivs.has(key)) map.delete(key);
    for (const key of actionImages.keys())
      if (key !== 'infantry' && !latestCivs.has(key)) actionImages.delete(key);
    for (const key of motionImages.keys()) if (!neededMotion.has(key)) motionImages.delete(key);
    for (const key of attackImages.keys()) if (!neededAttack.has(key)) attackImages.delete(key);
    for (const key of factionSiegeImages.keys())
      if (!neededSiege.includes(key)) factionSiegeImages.delete(key);
    if (!latestCivs.has('tang')) tangImpactImage = undefined;
    worldCache.clear();
    poseCache.clear();
    portraitCache.clear();
    loadRevision++;
    loadedCivKey = values.every(Boolean) ? civKey : '';
  }
  return serial === requestSerial && values.every(Boolean);
}

function lookup(type: string, civ: string): Entry | undefined {
  for (const key of KEYS) {
    const row = ROWS[key].findIndex(
      (entry) => entry.type === type && (type !== 'villager' || entry.civ === civ),
    );
    if (row >= 0) return { key, row, data: ROWS[key][row] };
  }
  if (type === 'villager') return { key: 'a', row: 0, data: ROWS.a[0] };
  return undefined;
}

/** Accepts simulation order aliases while keeping the rendering action set small. */
export function normalizeUnitAction(action = 'idle', activity = ''): UnitAction {
  action = action.toLowerCase();
  activity = activity.toLowerCase();
  if (['carry', 'carrying', 'deliver', 'delivery', 'haul'].includes(action)) return 'carry';
  if (['walk', 'move', 'moving', 'patrol', 'return', 'trade', 'follow'].includes(action))
    return 'walk';
  if (['attack', 'attacking', 'fight', 'combat'].includes(action)) return 'attack';
  if (['mine', 'mining'].includes(action)) return 'mine';
  if (['chop', 'chopping', 'woodcutting'].includes(action)) return 'chop';
  if (['build', 'building', 'repair', 'repairing'].includes(action)) return 'build';
  if (['harvest', 'harvesting', 'farm', 'farming'].includes(action)) return 'harvest';
  if (['hunt', 'hunting'].includes(action)) return 'hunt';
  if (['work', 'gather', 'gathering', 'working'].includes(action)) {
    if (['wood', 'tree', 'chop', 'lumber'].some((s) => activity.includes(s))) return 'chop';
    if (['gold', 'stone', 'mine', 'mining', 'ore'].some((s) => activity.includes(s))) return 'mine';
    if (['build', 'repair', 'construct'].some((s) => activity.includes(s))) return 'build';
    if (['hunt', 'animal', 'deer', 'boar', 'meat'].some((s) => activity.includes(s))) return 'hunt';
    return 'harvest';
  }
  return 'idle';
}

function physicalCanvas(width: number, height: number): HTMLCanvasElement {
  const canvas = document.createElement('canvas');
  canvas.width = Math.round(width * SPRITE_DPR);
  canvas.height = Math.round(height * SPRITE_DPR);
  return canvas;
}

interface SourcePose {
  image: HTMLImageElement;
  frame: Frame;
  scale: number;
  key: string;
  authored: boolean;
}
function sourceFor(
  entry: Entry,
  civ: string,
  action: UnitAction,
  phase: number,
  shot: number,
  activity = '',
): SourcePose | undefined {
  let image = images.get(entry.key);
  let frame = FRAMES[entry.key][entry.row * 4 + shot];
  let scale = entry.data.targetHeight / entry.data.bodyHeight;
  let key = 'base:' + entry.key + ':' + entry.row + ':' + shot;
  let authored = false;
  const contact = phase >= 2 ? 1 : 0;
  if (entry.data.type === 'trader') {
    const sheet = TRADER_SHEETS[civ],
      loaded = traderImages.get(civ);
    if (!sheet || !loaded) return undefined;
    const row = action === 'walk' ? contact : 0;
    return {
      image: loaded,
      frame: sheet.frames[row * 4 + shot],
      scale: 48 / (sheet.rowBodyHeights?.[row] ?? sheet.bodyHeight),
      key: 'trader:' + civ + ':' + row + ':' + shot,
      authored: true,
    };
  }
  if (
    (entry.data.type === 'villager' || entry.data.type === 'engineer') &&
    action === 'carry' &&
    carryImage
  ) {
    const row = CARRY_ROWS[entry.data.type === 'engineer' ? 'roman' : civ] ?? 0;
    const wood = carryResource(activity) === 'wood' && !!woodImage,
      sheet = wood ? WOOD_SHEET : CARRY_SHEET;
    return {
      image: wood ? woodImage! : carryImage,
      frame: sheet.frames[row * 4 + shot],
      scale: 48 / (sheet.rowBodyHeights?.[row] ?? sheet.bodyHeight),
      key: (wood ? 'cargo-wood:' : 'cargo:') + row + ':' + shot,
      authored: false,
    };
  }
  const posed = (
    id: string,
    row: number,
    targetHeight = entry.data.targetHeight,
  ): SourcePose | undefined => {
    const sheet = ATTACK_SHEETS[id],
      loaded = attackImages.get(id);
    if (!sheet || !loaded) return undefined;
    return {
      image: loaded,
      frame: sheet.frames[row * 4 + shot],
      scale: targetHeight / (sheet.rowBodyHeights?.[row] ?? sheet.bodyHeight),
      key: 'attack:' + id + ':' + row + ':' + shot,
      authored: true,
    };
  };
  if (SIEGE_TYPES.includes(entry.data.type)) {
    const row =
      action === 'attack' && phase !== 3 ? (phase === 2 ? 3 : 2) : action === 'walk' ? contact : 0;
    const id = civ + ':' + entry.data.type,
      sheet = FACTION_SIEGE[id],
      loaded = factionSiegeImages.get(id);
    if (sheet && loaded)
      return {
        image: loaded,
        frame: sheet.frames[row * 4 + shot],
        scale: 48 / sheet.crewHeight,
        key: 'faction-siege:' + id + ':' + row + ':' + shot,
        authored: true,
      };
    const siege = posed(entry.data.type, row);
    if (siege) return siege;
  }
  const bowClass = ['archer', 'guardarcher', 'horsearcher'].includes(entry.data.type);
  if (action === 'attack' && (phase !== 3 || bowClass || entry.data.type === 'musketeer')) {
    // Bow recovery keeps the extended release stance; gun recovery keeps its aimed stance.
    const impact = phase === 2 || (phase === 3 && bowClass) ? 1 : 0;
    const foot = ARMY_TYPES.indexOf(entry.data.type as (typeof ARMY_TYPES)[number]);
    const cavalry = MOUNTED_TYPES.indexOf(entry.data.type as (typeof MOUNTED_TYPES)[number]);
    if (entry.data.type === 'elephant') {
      const elephant = posed(phase === 2 ? 'elephant_impact' : 'elephant_windup', 0, 100);
      if (elephant) return elephant;
    }
    const spec = ATTACK_ROWS[entry.data.type];
    const attack =
      foot >= 0
        ? posed('foot_' + civ, foot * 2 + impact, 48)
        : cavalry >= 0
          ? posed('mounted_' + civ, cavalry * 2 + impact, 72)
          : spec
            ? posed(spec.sheet, spec.row + impact)
            : undefined;
    if (attack) return attack;
  }

  const armyType = ARMY_TYPES.indexOf(entry.data.type as (typeof ARMY_TYPES)[number]);
  if (armyType >= 0 && armyImages.has(civ)) {
    const row = armyType * 2 + (action === 'walk' ? contact : 0),
      sheet = ARMY_SHEETS[civ];
    return {
      image: armyImages.get(civ)!,
      frame: sheet.frames[row * 4 + shot],
      scale: 48 / (sheet.rowBodyHeights?.[row] ?? sheet.bodyHeight),
      key: 'army:' + civ + ':' + row + ':' + shot + ':' + (action === 'walk' ? 'stride' : 'stance'),
      authored: action === 'walk' || action === 'attack',
    };
  }
  const mountedType = MOUNTED_TYPES.indexOf(entry.data.type as (typeof MOUNTED_TYPES)[number]);
  if (mountedType >= 0 && mountedImages.has(civ)) {
    const row = mountedType * 2 + (action === 'walk' ? contact : 0),
      sheet = MOUNTED_SHEETS[civ];
    return {
      image: mountedImages.get(civ)!,
      frame: sheet.frames[row * 4 + shot],
      scale: 72 / (sheet.rowBodyHeights?.[row] ?? sheet.bodyHeight),
      key:
        'mounted:' + civ + ':' + row + ':' + shot + ':' + (action === 'walk' ? 'stride' : 'stance'),
      authored: action === 'walk' || action === 'attack',
    };
  }
  const motion = MOTION_ROWS[entry.data.type];
  if (motion && motionImages.has(motion.sheet)) {
    const row = motion.row + (action === 'walk' ? contact : 0),
      sheet = MOTION_SHEETS[motion.sheet];
    return {
      image: motionImages.get(motion.sheet)!,
      frame: sheet.frames[row * 4 + shot],
      scale: entry.data.targetHeight / (sheet.rowBodyHeights?.[row] ?? sheet.bodyHeight),
      key:
        'motion:' +
        motion.sheet +
        ':' +
        row +
        ':' +
        shot +
        ':' +
        (action === 'walk' ? 'stride' : 'stance'),
      authored: action === 'walk' || action === 'attack',
    };
  }
  if (entry.data.type === 'elephant') {
    const id = 'elephant_' + (action === 'walk' ? ['a', 'b', 'c', 'b'][phase] : 'a'),
      sheet = MOTION_SHEETS[id],
      loaded = motionImages.get(id);
    if (loaded)
      return {
        image: loaded,
        frame: sheet.frames[shot],
        scale: 100 / sheet.bodyHeight,
        key: 'motion:' + id + ':' + shot + ':' + (action === 'walk' ? 'stride' : 'stance'),
        authored: action === 'walk' || action === 'attack',
      };
  }

  const workerSheet = SHEETS[civ as SheetKey] && civ !== 'infantry' ? (civ as SheetKey) : 'roman';
  const toolRow = TOOL_ROWS[civ];
  const unladen = action === 'idle' || action === 'walk';
  if (entry.data.type === 'villager' && action === 'carry' && carryImage) {
    const row = CARRY_ROWS[civ] ?? 0;
    const wood = carryResource(activity) === 'wood' && !!woodImage;
    const sheet = wood ? WOOD_SHEET : CARRY_SHEET;
    image = wood ? woodImage! : carryImage;
    frame = sheet.frames[row * 4 + shot];
    scale = 48 / (sheet.rowBodyHeights?.[row] ?? sheet.bodyHeight);
    key = (wood ? 'carry-wood:' : 'carry:') + row + ':' + shot;
  } else if (entry.data.type === 'villager' && unladen && toolRow !== undefined && toolImage) {
    const row = toolRow + (action === 'walk' ? 1 + contact : 0);
    image = toolImage;
    frame = TOOL_SHEET.frames[row * 4 + shot];
    scale = 48 / (TOOL_SHEET.rowBodyHeights?.[row] ?? TOOL_SHEET.bodyHeight);
    key = 'unladen:' + row + ':' + shot;
    authored = action === 'walk';
  } else if (
    entry.data.type === 'villager' &&
    action !== 'carry' &&
    actionImages.has(workerSheet)
  ) {
    const tang = workerSheet === 'tang';
    let row = unladen && toolRow !== undefined ? 2 : contact;
    if (action === 'mine') row = tang ? 2 : 2 + contact;
    else if (action === 'chop' || action === 'attack' || action === 'hunt')
      row = tang ? 3 + contact : 4 + contact;
    else if (action === 'build') row = tang ? 5 : 6;
    else if (action === 'harvest' || action === 'work') row = tang ? 6 : 7;
    const sheet = SHEETS[workerSheet];
    image = actionImages.get(workerSheet)!;
    frame = sheet.frames[row * 4 + shot];
    scale = 48 / sheet.bodyHeight;
    key = 'worker:' + workerSheet + ':' + row + ':' + shot;
    if (
      tang &&
      contact === 1 &&
      tangImpactImage &&
      ['mine', 'chop', 'attack', 'hunt'].includes(action)
    ) {
      const impactRow = action === 'mine' ? 0 : 1;
      image = tangImpactImage;
      frame = TANG_IMPACT.frames[impactRow * 4 + shot];
      scale = 48 / TANG_IMPACT.bodyHeight;
      key = 'worker:tang-impact:' + impactRow + ':' + shot;
    }
    authored = true;
  } else if (
    (action === 'walk' || entry.data.type === 'legionary') &&
    actionImages.has('infantry')
  ) {
    const rows: Record<string, number> = { spear: 0, sword: 2, archer: 4, legionary: 6 };
    const row = rows[entry.data.type];
    if (row !== undefined) {
      const sheet = SHEETS.infantry;
      image = actionImages.get('infantry')!;
      frame = sheet.frames[(row + (action === 'walk' ? contact : 0)) * 4 + shot];
      // Spear tips are excluded from body size, keeping the adult anatomy consistent.
      const bodyRef =
        row === 0
          ? sheet.bodyHeight * 0.85
          : row === 6
            ? sheet.bodyHeight * 0.88
            : sheet.bodyHeight * 0.9;
      scale = 48 / bodyRef;
      key = 'infantry:' + row + ':' + (action === 'walk' ? contact : 0) + ':' + shot;
      authored = true;
    }
  }
  return image ? { image, frame, scale, key, authored } : undefined;
}

function poseFor(
  entry: Entry,
  civ: string,
  action: UnitAction,
  phase: number,
  shot: number,
  activity = '',
): Pose | undefined {
  const source = sourceFor(entry, civ, action, phase, shot, activity);
  if (!source) return undefined;
  const { image, frame, scale, authored } = source;
  const key = source.key + (authored ? '|authored' : '|rest');
  const cached = cacheGet(poseCache, key);
  if (cached) return cached;
  const elephant = entry.data.type === 'elephant';
  const siege = SIEGE_TYPES.includes(entry.data.type);
  const width = elephant || siege ? 224 : 128,
    height = siege ? 224 : elephant ? 208 : 136;
  const anchorX = elephant || siege ? 112 : 64,
    anchorY = siege ? 196 : elephant ? 182 : 112;
  const canvas = physicalCanvas(width, height);
  const c = canvas.getContext('2d');
  if (!c) return undefined;
  c.scale(SPRITE_DPR, SPRITE_DPR);
  c.imageSmoothingEnabled = true;
  c.imageSmoothingQuality = 'high';
  const [, , sw, sh, px, py] = frame;
  const isolated = isolatedFrame(image, frame);
  c.drawImage(
    isolated,
    0,
    0,
    sw,
    sh,
    anchorX - px * scale,
    anchorY - py * scale,
    sw * scale,
    sh * scale,
  );
  const trimmed = trimSprite(canvas, anchorX * SPRITE_DPR, anchorY * SPRITE_DPR);
  const padded = physicalCanvas(trimmed.logicalWidth + 24, trimmed.logicalHeight + 24),
    painter = padded.getContext('2d')!;
  painter.imageSmoothingEnabled = false;
  painter.drawImage(trimmed.canvas, 12 * SPRITE_DPR, 12 * SPRITE_DPR);
  const result = {
    canvas: padded,
    logicalWidth: padded.width / SPRITE_DPR,
    logicalHeight: padded.height / SPRITE_DPR,
    anchorX: trimmed.anchorX / SPRITE_DPR + 12,
    anchorY: trimmed.anchorY / SPRITE_DPR + 12,
    authored,
  };
  cachePut(poseCache, key, result, CACHE_LIMITS.poses);
  return result;
}

function drawPose(c: CanvasRenderingContext2D, pose: Pose) {
  // This is a 1:1 physical-pixel blit under the DPR transform, never another filter pass.
  c.imageSmoothingEnabled = false;
  c.drawImage(
    pose.canvas,
    0,
    0,
    pose.canvas.width,
    pose.canvas.height,
    0,
    0,
    pose.logicalWidth,
    pose.logicalHeight,
  );
}

function muzzle(
  c: CanvasRenderingContext2D,
  x: number,
  y: number,
  dx: number,
  dy: number,
  phase: number,
  cannon: boolean,
) {
  if (phase !== 2) return;
  const radius = cannon ? 8 : 4;
  const glow = c.createRadialGradient(x, y, 0, x, y, radius);
  glow.addColorStop(0, 'rgba(248,220,155,.80)');
  glow.addColorStop(0.28, 'rgba(229,160,83,.55)');
  glow.addColorStop(1, 'rgba(229,160,83,0)');
  c.fillStyle = glow;
  c.beginPath();
  c.ellipse(x, y, radius, radius * 0.5, 0, 0, Math.PI * 2);
  c.fill();
  const smoke = c.createRadialGradient(
    x + dx * 4,
    y + dy * 4,
    1,
    x + dx * 7,
    y + dy * 7,
    radius * 1.4,
  );
  smoke.addColorStop(0, 'rgba(184,185,170,.35)');
  smoke.addColorStop(1, 'rgba(184,185,170,0)');
  c.fillStyle = smoke;
  c.beginPath();
  c.ellipse(x + dx * 7, y + dy * 7, radius * 1.4, radius * 0.75, 0, 0, Math.PI * 2);
  c.fill();
}

/** Small material tag on the closed carry sack; never drawn for idle, walk or work. */
function cargoTag(c: CanvasRenderingContext2D, pose: Pose, resource: CarryResource, shot: number) {
  if (resource === 'wood' && woodImage) return;
  const x = pose.anchorX + (shot === 0 || shot === 2 ? 2 : -2),
    y = pose.anchorY - 26;
  c.save();
  c.translate(x, y);
  c.strokeStyle = '#72593c';
  c.lineWidth = 0.5;
  if (resource === 'food') {
    c.fillStyle = '#c6aa6a';
    for (const [gx, gy] of [
      [-1.7, -0.4],
      [0, -0.9],
      [1.5, -0.2],
      [-0.6, 0.8],
      [1.2, 0.9],
    ]) {
      c.beginPath();
      c.ellipse(gx, gy, 0.7, 0.4, -0.4, 0, Math.PI * 2);
      c.fill();
    }
  } else if (resource === 'meat') {
    c.fillStyle = '#98614e';
    c.beginPath();
    c.ellipse(0, 0, 2.4, 1.5, -0.2, 0, Math.PI * 2);
    c.fill();
    c.strokeStyle = '#d7bd9f';
    c.beginPath();
    c.moveTo(-1.5, -0.4);
    c.lineTo(1.4, 0.4);
    c.stroke();
  } else if (resource === 'wood') {
    c.strokeStyle = '#6d482e';
    c.lineWidth = 1;
    for (const yy of [-1, 0, 1]) {
      c.beginPath();
      c.moveTo(-2.3, yy);
      c.lineTo(2.3, yy - 0.6);
      c.stroke();
    }
    c.fillStyle = '#d0a372';
    c.beginPath();
    c.ellipse(-2.3, 0.2, 0.65, 1.4, -0.15, 0, Math.PI * 2);
    c.fill();
  } else if (resource === 'gold' || resource === 'stone') {
    c.fillStyle = resource === 'gold' ? '#d3b055' : '#99a19b';
    c.beginPath();
    c.moveTo(-2.5, 1);
    c.lineTo(-1.1, -1.8);
    c.lineTo(1, -1.4);
    c.lineTo(2.4, 0.7);
    c.closePath();
    c.fill();
    c.strokeStyle = resource === 'gold' ? '#f0cf79' : '#c6cdc3';
    c.beginPath();
    c.moveTo(-1, -1);
    c.lineTo(0.6, -0.9);
    c.stroke();
  } else {
    c.strokeStyle = '#ded0ac';
    c.beginPath();
    c.moveTo(-1.5, 1);
    c.lineTo(1.5, -1);
    c.moveTo(-1.5, -1);
    c.lineTo(1.5, 1);
    c.stroke();
  }
  c.restore();
}

/** Every animation draws one intact pose. No rectangular masks, detached limbs or resized body parts. */
function drawAnimatedPose(
  c: CanvasRenderingContext2D,
  pose: Pose,
  data: Row,
  action: UnitAction,
  phase: number,
  shot: number,
  resource: CarryResource,
) {
  const side = shot === 0 || shot === 2 ? 1 : -1;
  const front = shot < 2 ? 0.45 : -0.45;
  const gait = [0, 1, 0, -1][phase];
  const impact = [0, 0.5, 1, 0.2][phase];
  let tx = 0,
    ty = 0;
  if (action === 'walk' || action === 'carry') {
    // Authored contacts supply the actual leg poses. Unsupported classes keep a tiny whole-body gait fallback.
    tx = pose.authored ? 0 : side * gait * 0.5;
    ty = pose.authored ? 0 : -Math.abs(gait) * 0.5;
  } else if (action === 'attack' || action === 'hunt') {
    const firearm = data.type === 'cannon' || data.type === 'musketeer';
    tx =
      side *
      impact *
      (data.type === 'cannon' ? -2.2 : firearm ? -0.7 : data.type === 'ram' ? 2 : 0.8);
    ty = front * impact * (firearm ? -0.5 : 0.45);
    if (pose.authored) {
      tx = 0;
      ty = 0;
    }
  } else if (action !== 'idle') {
    ty = phase === 1 ? 0.5 : phase === 3 ? -0.5 : 0;
  }
  tx = Math.round(tx * SPRITE_DPR) / SPRITE_DPR;
  ty = Math.round(ty * SPRITE_DPR) / SPRITE_DPR;
  c.save();
  c.translate(tx, ty);
  drawPose(c, pose);
  if (action === 'carry') cargoTag(c, pose, resource, shot);
  c.restore();
  if (action === 'attack' && !pose.authored && data.type === 'cannon')
    muzzle(
      c,
      pose.anchorX + side * 25 + tx,
      pose.anchorY - 22 + front * 12,
      side,
      front,
      phase,
      true,
    );
  if (action === 'attack' && !pose.authored && data.type === 'musketeer')
    muzzle(
      c,
      pose.anchorX + side * 24 + tx,
      pose.anchorY - data.targetHeight * 0.45,
      side,
      front,
      phase,
      false,
    );
}

/** Runtime alpha trim only: source PNGs stay untouched, and all nonzero-alpha effects are retained. */
function trimSprite(canvas: HTMLCanvasElement, anchorX: number, anchorY: number): UnitArtSprite {
  const context = canvas.getContext('2d')!;
  const pixels = context.getImageData(0, 0, canvas.width, canvas.height).data;
  let left = canvas.width,
    top = canvas.height,
    right = -1,
    bottom = -1;
  for (let y = 0; y < canvas.height; y++) {
    for (let x = 0; x < canvas.width; x++) {
      if (pixels[(y * canvas.width + x) * 4 + 3] === 0) continue;
      if (x < left) left = x;
      if (x > right) right = x;
      if (y < top) top = y;
      if (y > bottom) bottom = y;
    }
  }
  if (right < left)
    return {
      canvas,
      anchorX,
      anchorY,
      pixelRatio: SPRITE_DPR,
      logicalWidth: canvas.width / SPRITE_DPR,
      logicalHeight: canvas.height / SPRITE_DPR,
    };
  const padding = SPRITE_DPR * 2;
  left = Math.max(0, left - padding);
  top = Math.max(0, top - padding);
  right = Math.min(canvas.width - 1, right + padding);
  bottom = Math.min(canvas.height - 1, bottom + padding);
  const cropped = document.createElement('canvas');
  cropped.width = right - left + 1;
  cropped.height = bottom - top + 1;
  const draw = cropped.getContext('2d')!;
  draw.imageSmoothingEnabled = false;
  draw.drawImage(
    canvas,
    left,
    top,
    cropped.width,
    cropped.height,
    0,
    0,
    cropped.width,
    cropped.height,
  );
  return {
    canvas: cropped,
    anchorX: anchorX - left,
    anchorY: anchorY - top,
    pixelRatio: SPRITE_DPR,
    logicalWidth: cropped.width / SPRITE_DPR,
    logicalHeight: cropped.height / SPRITE_DPR,
  };
}

export function renderUnitAtlas(
  type: string,
  civ: string,
  age: number,
  team: number,
  frame: number,
  dir: number,
  action = 'idle',
  activity = '',
): UnitArtSprite | undefined {
  void age;
  const renderer = civilizationRenderer(civ);
  if (renderer)
    return renderer.renderUnit(
      type,
      team,
      frame,
      dir,
      normalizeUnitAction(action, activity),
      activity,
    );
  const entry = lookup(type, civ);
  if (!entry) return undefined;
  frame = ((Math.round(frame) % 4) + 4) % 4;
  dir = ((Math.round(dir) % 8) + 8) % 8;
  const animation = normalizeUnitAction(action, activity),
    shot = DIR_TO_SHOT[dir];
  if (animation === 'idle') frame = 0;
  const resource = animation === 'carry' ? carryResource(activity) : 'generic';
  const artCiv =
    type === 'villager' || CIV_COMMON_TYPES.includes(type) ? civ : entry.data.civ || 'shared';
  const key = [
    entry.key,
    entry.row,
    artCiv,
    shot,
    team === 0 ? 0 : 1,
    frame,
    animation,
    resource,
    actionImages.size,
    tangImpactImage ? 1 : 0,
    toolImage ? 1 : 0,
    carryImage ? 1 : 0,
    woodImage ? 1 : 0,
    armyImages.size,
    loadRevision,
  ].join(':');
  const cached = cacheGet(worldCache, key);
  if (cached) return cached;
  const pose = poseFor(entry, civ, animation, frame, shot, activity);
  if (!pose) return undefined;
  const canvas = physicalCanvas(pose.logicalWidth, pose.logicalHeight);
  const c = canvas.getContext('2d');
  if (!c) return undefined;
  c.scale(SPRITE_DPR, SPRITE_DPR);
  c.imageSmoothingEnabled = true;
  c.imageSmoothingQuality = 'high';
  drawAnimatedPose(c, pose, entry.data, animation, frame, shot, resource);
  const result = trimSprite(canvas, pose.anchorX * SPRITE_DPR, pose.anchorY * SPRITE_DPR);
  cachePut(worldCache, key, result, CACHE_LIMITS.sprites);
  return result;
}

/** Portraits sample original source pixels directly and remain independent of world scale. */
export function renderUnitPortrait(
  type: string,
  civ: string,
  age: number,
): HTMLCanvasElement | undefined {
  void age;
  const renderer = civilizationRenderer(civ);
  if (renderer) return renderer.renderPortrait(type);
  const entry = lookup(type, civ);
  if (!entry) return undefined;
  const source = sourceFor(entry, civ, 'idle', 0, 0);
  if (!source) return undefined;
  const image = source.image;
  const key = source.key;
  const cached = cacheGet(portraitCache, key);
  if (cached) return cached;
  const [, , sw, sh] = source.frame;
  const canvas = document.createElement('canvas');
  canvas.width = 512;
  canvas.height = 576;
  const c = canvas.getContext('2d');
  if (!c) return undefined;
  c.imageSmoothingEnabled = true;
  c.imageSmoothingQuality = 'high';
  const scale = Math.min(448 / sw, 528 / sh),
    w = sw * scale,
    h = sh * scale;
  c.drawImage(isolatedFrame(image, source.frame), 0, 0, sw, sh, (512 - w) / 2, 552 - h, w, h);
  cachePut(portraitCache, key, canvas, CACHE_LIMITS.portraits);
  return canvas;
}
